#!/usr/bin/env python3
"""Seed the showcase Vikunja with synthetic content through its REST API (idempotent).

Registers "rea-admin" and three crew accounts (ada-finch, rui-castellanos, mina-okafor); their passwords are generated by
up.sh into ~/capture/vikunja/.admin (mode 600). Each account sets its display name, and content is created by the account
that would own it, so creator fields differ: rea-admin creates 5 projects (one child, one archived), 3 labels, the shares and
1 saved filter; Ada and Rui each create a team (adding rea-admin); Ada, Rui and Mina create the tasks of the projects shared
with them and comment on them; rea-admin applies labels, assignees and a task relation. Uses the legacy /api/v1 (PUT creates,
POST updates), which 2.x still serves; the capture uses the web UI's /api/v2. Writes seed-ids.json (ids only).
Never prints a credential."""
import json, os, sys, time, urllib.error, urllib.parse, urllib.request

BASE = os.environ.get("BASE_URL", "http://127.0.0.1:3211"); A = BASE + "/api/v1"
DIR = os.environ.get("CAPTURE_DIR", os.path.expanduser("~/capture/vikunja"))
adm = dict(l.split("=", 1) for l in open(os.path.join(DIR, ".admin")).read().splitlines() if "=" in l)
PW = {"rea-admin": adm["VIKUNJA_ADMIN_PASSWORD"], **{u: adm["VIKUNJA_CREW_PASSWORD"] for u in ("ada-finch", "rui-castellanos", "mina-okafor")}}
NAMES = {"rea-admin": "Rea Admin", "ada-finch": "Ada Finch", "rui-castellanos": "Rui Castellanos", "mina-okafor": "Mina Okafor"}
TOK = {}

def log(msg): print(f"[seed] {msg}", file=sys.stderr)

def api(method, path, body=None, ok=(), as_user=None):
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(A + path, data=data, method=method)
    req.add_header("Accept", "application/json")
    if data is not None: req.add_header("Content-Type", "application/json")
    if as_user: req.add_header("Authorization", "Bearer " + TOK[as_user])
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            raw = r.read(); return (json.loads(raw) if raw else None), r.status
    except urllib.error.HTTPError as e:
        if e.code in ok: return None, e.code
        raise SystemExit(f"[seed] {method} {path} as {as_user} -> {e.code}: {e.read().decode(errors='replace')[:300]}")

def wait_ready():
    for _ in range(120):
        try:
            with urllib.request.urlopen(A + "/info", timeout=5) as r:
                if r.status == 200: return json.loads(r.read())
        except Exception: pass
        time.sleep(2)
    raise SystemExit("[seed] Vikunja did not become ready")

info = wait_ready(); log(f"vikunja {info.get('version')} ready at {BASE}")
for u in PW:
    tok, st = api("POST", "/login", {"username": u, "password": PW[u], "long_token": True}, ok=(400, 401, 403, 404, 412))
    if tok is None:
        email = u.replace("-", ".", 1) + "@example.test"   # usernames may not contain dots; emails keep first.last
        api("POST", "/register", {"username": u, "email": email, "password": PW[u]}); log(f"user {u} registered")
        tok, _ = api("POST", "/login", {"username": u, "password": PW[u], "long_token": True})
    TOK[u] = tok["token"]
    me, _ = api("GET", "/user", as_user=u)
    if me.get("name") != NAMES[u]:
        api("POST", "/user/settings/general", {**(me.get("settings") or {}), "name": NAMES[u], "email_reminders_enabled": False, "timezone": "UTC"}, as_user=u)
ADM = "rea-admin"
users = {u: api("GET", "/user", as_user=u)[0]["id"] for u in PW}
ids = {"version": info.get("version"), "users": users, "projects": {}, "views": {}, "labels": {}, "tasks": {}, "comments": {}, "teams": {}, "filters": {}}

def all_projects(user=ADM):
    out, page = [], 1
    while True:
        lst, _ = api("GET", f"/projects?is_archived=true&page={page}&per_page=50", as_user=user)
        out += lst or []
        if not lst or len(lst) < 50: return out
        page += 1

# Remove scratch tasks left by an interrupted capture so every capture starts from the same state.
for t in api("GET", "/tasks?s=Rea%20scratch&per_page=50", as_user=ADM)[0] or []:
    if t["title"].startswith("Rea scratch"): api("DELETE", f"/tasks/{t['id']}", as_user=ADM); log(f"removed leftover scratch task {t['id']}")

PROJECTS = [("Lighthouse Rota", "Night-watch planning for the lamp gallery and the tide tables.", None, False),
            ("Lamp Room Upkeep", "Wicks, lens cloths and brass polish for the Fresnel lens.", "Lighthouse Rota", False),
            ("Granite Ledger", "Quarterly stone counts for the north quarry and the tidal yard.", None, False),
            ("Blue Heron Kitchen", "Menu planning that follows the spring tides, 36 covers a sitting.", None, False),
            ("Copperfield Annex Repaint", "Repainting the lamp gallery railings; finished in the spring.", None, True)]
existing = {p["title"]: p for p in all_projects()}
for title, desc, parent, archived in PROJECTS:
    p = existing.get(title)
    if not p:
        body = {"title": title, "description": desc, **({"parent_project_id": ids["projects"][parent]} if parent else {})}
        p, _ = api("PUT", "/projects", body, as_user=ADM); log(f"project {title} created")
        if archived: p, _ = api("POST", f"/projects/{p['id']}", {**p, "is_archived": True}, as_user=ADM); log(f"project {title} archived")
    ids["projects"][title] = p["id"]
    ids["views"][title] = {v["title"]: v["id"] for v in (api("GET", f"/projects/{p['id']}/views", as_user=ADM)[0] or [])}
P = ids["projects"]

LABELS = [("tide-critical", "Must be finished before the next spring tide.", "c0392b"),
          ("quarry-audit", "Part of the quarterly Granite Ledger audit.", "7f8c8d"),
          ("kelp-order", "Needs a supply order from the Saltmarsh Depot.", "27ae60")]
have = {l["title"]: l for l in (api("GET", "/labels?per_page=50", as_user=ADM)[0] or [])}
for title, desc, color in LABELS:
    ids["labels"][title] = (have.get(title) or api("PUT", "/labels", {"title": title, "description": desc, "hex_color": color}, as_user=ADM)[0])["id"]

# Teams are created by a crew member, who adds rea-admin so the admin can share projects with the team.
TEAMS = [("Night Watch", "Keepers of the lamp from 22:00 to 06:00.", "ada-finch", "Lighthouse Rota"),
         ("Quarry Auditors", "Stone counters for the Granite Ledger.", "rui-castellanos", "Granite Ledger")]
for name, desc, owner, proj in TEAMS:
    t = next((x for x in (api("GET", "/teams?per_page=50", as_user=owner)[0] or []) if x["name"] == name), None)
    if not t: t, _ = api("PUT", "/teams", {"name": name, "description": desc}, as_user=owner); log(f"team {name} created by {owner}")
    ids["teams"][name] = t["id"]
    api("PUT", f"/teams/{t['id']}/members", {"username": ADM}, ok=(400, 409), as_user=owner)
    api("PUT", f"/projects/{P[proj]}/teams", {"team_id": t["id"], "permission": 1}, ok=(400, 409), as_user=ADM)
api("PUT", f"/projects/{P['Blue Heron Kitchen']}/users", {"username": "mina-okafor", "permission": 1}, ok=(400, 409), as_user=ADM)

TASKS = [("Draft the January night-shift rota", "Shift three runs 22:00 to 06:00; Ada Finch keeps the tide tables.", "Lighthouse Rota", "ada-finch",
          3, "2027-01-05T18:00:00Z", False, 0, ["tide-critical"], ["ada-finch"]),
         ("Log the lamp oil budget", "Winter budget is 180 litres of lamp oil.", "Lighthouse Rota", "ada-finch", 2, None, False, 0, [], []),
         ("Trim the wicks before dusk", "Use the brass trimmer and note each wick length in the night book.", "Lamp Room Upkeep", ADM,
          1, None, True, 0, [], ["ada-finch"]),
         ("Count the blocks in the tidal yard", "97 blocks expected after the October storm; ledger page 2291.", "Granite Ledger", "rui-castellanos",
          4, "2026-11-14T09:00:00Z", False, 0, ["quarry-audit"], ["rui-castellanos"]),
         ("Retire cart number 7", "The axle on cart number 7 is bent; move its load to cart 9.", "Granite Ledger", "rui-castellanos", 2, None, True, 0, [], []),
         ("Order smoked kelp from the Saltmarsh Depot", "Twelve crates for the spring-tide menu.", "Blue Heron Kitchen", "mina-okafor",
          3, "2026-11-20T12:00:00Z", False, 0, ["kelp-order", "tide-critical"], ["mina-okafor"]),
         ("Print the tide-table menu cards", "Thirty-six cards, one per cover, on heron-grey stock.", "Blue Heron Kitchen", "mina-okafor", 1, None, False, 0.5, [], [])]
for title, desc, proj, creator, prio, due, done, pct, labels, assignees in TASKS:
    found = [t for t in (api("GET", f"/tasks?s={urllib.parse.quote(title)}&per_page=50", as_user=ADM)[0] or []) if t["title"] == title]
    if found: t = found[0]
    else:
        body = {"title": title, "description": desc, "priority": prio, "done": done, "percent_done": pct, **({"due_date": due} if due else {})}
        t, _ = api("PUT", f"/projects/{P[proj]}/tasks", body, as_user=creator); log(f"task {title} created by {creator}")
    full, _ = api("GET", f"/tasks/{t['id']}", as_user=ADM)
    have_l = {x["id"] for x in full.get("labels") or []}; have_a = {x["id"] for x in full.get("assignees") or []}
    for lb in labels:
        if ids["labels"][lb] not in have_l: api("PUT", f"/tasks/{t['id']}/labels", {"label_id": ids["labels"][lb]}, as_user=ADM)
    for a in assignees:
        if users[a] not in have_a: api("PUT", f"/tasks/{t['id']}/assignees", {"user_id": users[a]}, as_user=ADM)
    ids["tasks"][title] = t["id"]
T = ids["tasks"]
api("PUT", f"/tasks/{T['Count the blocks in the tidal yard']}/relations", {"other_task_id": T["Retire cart number 7"], "relation_kind": "related"},
    ok=(400, 409), as_user=ADM)

COMMENTS = [("Count the blocks in the tidal yard", "rui-castellanos", "Counted 97 blocks on the fourteenth; two are cracked."),
            ("Order smoked kelp from the Saltmarsh Depot", "mina-okafor", "The depot confirmed it can deliver on Thursday.")]
for task, who, text in COMMENTS:
    cur = [c for c in (api("GET", f"/tasks/{T[task]}/comments", as_user=who)[0] or []) if c["comment"] == text]
    ids["comments"][task] = (cur[0] if cur else api("PUT", f"/tasks/{T[task]}/comments", {"comment": text}, as_user=who)[0])["id"]

FILTER = {"title": "Tide-critical open work", "description": "Open tasks that carry the tide-critical label.",
          "filters": {"filter": f"done = false && labels in {ids['labels']['tide-critical']}", "filter_include_nulls": False}}
fl = [p for p in all_projects() if p["title"] == FILTER["title"]]
if fl: ids["filters"][FILTER["title"]] = -fl[0]["id"] - 1   # saved filters show up as pseudo-projects with id -(filter_id+1)
else: f, _ = api("PUT", "/filters", FILTER, as_user=ADM); ids["filters"][FILTER["title"]] = f["id"]; log("saved filter created")
json.dump(ids, open(os.path.join(DIR, "seed-ids.json"), "w"), indent=1)
log("seed-ids.json written: " + json.dumps(ids))
